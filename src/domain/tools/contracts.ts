export type ToolCallRequest = {
  /**
   * Provider/protocol call id. It must be returned unchanged to the originating model.
   * ProviderCallId is not guaranteed to be unique across the whole product Run and
   * never replaces the internal invocation identity.
   */
  readonly providerCallId: string;
  /**
   * Authoritative Synech invocation identity. Generated by Ordinary when the
   * call is accepted, stable for retry/UI reconnect, and never derived from the
   * provider id. Always present on every accepted tool call.
   */
  readonly invocationId: string;
  /** Invocation identity of the parent tool call, when this is a nested delegation. */
  readonly parentInvocationId?: string;
  readonly toolName: string;
  readonly input: ToolFactValue | undefined;
};

/**
 * Provider-side tool call as the model emits it: the external call id from the
 * model protocol, the tool name, and the raw input. No Synech-owned identity
 * is attached at this layer. The owning feature (Ordinary) mints the
 * `invocationId` when it accepts the call.
 *
 * `parentInvocationId` is set by the delegated AgentTool loop when the call is
 * nested under a delegated AgentTool invocation. It is an execution-context
 * field, not a model-bound identity, so it stays on this binding-side type.
 */
export type ProviderToolCall = {
  readonly providerCallId: string;
  readonly toolName: string;
  readonly input: ToolFactValue | undefined;
  /** Set on a tool call nested inside a delegated AgentTool invocation. */
  readonly parentInvocationId?: string;
  /**
   * Per-message token from the model loop (typically the durable Session entry
   * id of the assistant message). Mixed into the Synech invocation identity so
   * the same provider call id reused across different model rounds inside one
   * run does not collide.
   */
  readonly roundId: string;
};

/**
 * Tool call bound to a Synech invocation. Same shape as `ProviderToolCall`
 * with the addition of the Synech-owned `invocationId`. Carried through
 * Ordinary and the tool runtime, never on the model boundary.
 */
export type AcceptedToolInvocation = ProviderToolCall & {
  readonly invocationId: string;
};

