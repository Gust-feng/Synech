/** Resolves the authoritative Synech invocation identity for any accepted tool call fact. */
export function toolInvocationId(value: Pick<ToolCallRequest, "invocationId">): string {
  return value.invocationId;
}

/**
 * Two tool call facts describe the same invocation when they share the
 * authoritative `invocationId`. Provider call id, name, input, and parent
 * identity are not part of the identity decision.
 */
export function sameInvocationIdentity(
  left: Pick<ToolCallRequest, "invocationId">,
  right: Pick<ToolCallRequest, "invocationId">,
): boolean {
  return left.invocationId === right.invocationId;
}

/**
 * Two tool call facts describe the same definition when they agree on the
 * provider call id, tool name, input, and parent invocation identity.
 * Useful when the model adapter re-emits the assistant message and Ordinary
 * needs to confirm it is the same logical call before re-binding.
 */
export function sameInvocationDefinition(
  left: Pick<ToolCallRequest, "providerCallId" | "toolName" | "input" | "parentInvocationId">,
  right: Pick<ToolCallRequest, "providerCallId" | "toolName" | "input" | "parentInvocationId">,
): boolean {
  return left.providerCallId === right.providerCallId
    && left.toolName === right.toolName
    && left.parentInvocationId === right.parentInvocationId
    && sameToolInput(left.input, right.input);
}

/**
 * Two tool result facts describe the same result identity when they share the
 * `invocationId`. Status, output, error, and runtime metadata are excluded.
 */
export function sameToolResultIdentity(
  left: Pick<ToolCallResult, "invocationId">,
  right: Pick<ToolCallResult, "invocationId">,
): boolean {
  return left.invocationId === right.invocationId;
}

/**
 * Two tool result facts describe the same content when their business-meaning
 * fields match. Runtime fields (durationMs, timing, transport-only envelopes)
 * and identity fields (invocationId, providerCallId) are excluded; UI fields
 * (display, summary) are excluded by the fact that result content does not
 * carry them.
 */
export function sameToolResultContent(
  left: Pick<ToolCallResult, "status" | "output" | "error" | "errorDomain" | "errorFacts" | "failureAttribution" | "modelAttachmentRefs" | "delegatedExecution" | "parentInvocationId">,
  right: Pick<ToolCallResult, "status" | "output" | "error" | "errorDomain" | "errorFacts" | "failureAttribution" | "modelAttachmentRefs" | "delegatedExecution" | "parentInvocationId">,
): boolean {
  return left.status === right.status
    && sameToolInput(left.output, right.output)
    && left.error === right.error
    && left.errorDomain === right.errorDomain
    && sameErrorFacts(left.errorFacts, right.errorFacts)
    && left.failureAttribution === right.failureAttribution
    && left.parentInvocationId === right.parentInvocationId
    && sameAttachmentRefs(left.modelAttachmentRefs, right.modelAttachmentRefs)
    && sameDelegatedExecution(left.delegatedExecution, right.delegatedExecution);
}

/**
 * Idempotency comparison for a tool result re-delivery. Returns true only when
 * the two results agree on the authoritative invocation, the call definition
 * (toolName, input, parentInvocationId), the approval request (if any), and
 * the business-meaning result content. Used to decide whether an incoming
 * re-delivery of the same invocation can be silently dropped; a different
 * `toolName` or `input` for the same `invocationId` is treated as a real
 * conflict, not an idempotent match, so a stale approval cannot survive a
 * call-definition change.
 */
export function sameResultForIdempotency(
  left: ToolCallResult,
  right: ToolCallResult,
): boolean {
  if (!sameToolResultIdentity(left, right)) return false;
  if (left.toolName !== right.toolName) return false;
  if (left.parentInvocationId !== right.parentInvocationId) return false;
  if (!sameToolInput(left.input, right.input)) return false;
  return sameConfirmationRequestShape(left.confirmationRequest, right.confirmationRequest)
    && sameToolResultContent(left, right);
}

function sameConfirmationRequestShape(
  left: ConfirmationRequest | undefined,
  right: ConfirmationRequest | undefined,
): boolean {
  if (left === right) return true;
  if (left === undefined || right === undefined) return false;
  return left.confirmationId === right.confirmationId
    && left.invocationId === right.invocationId
    && left.title === right.title
    && left.actionSummary === right.actionSummary
    && left.consequence === right.consequence
    && left.riskLevel === right.riskLevel
    && left.requestedAt === right.requestedAt
    && left.expiresAt === right.expiresAt
    && left.resumeAvailability === right.resumeAvailability
    && sameStringList(left.affectedResources, right.affectedResources)
    && sameStringList(left.sourceRefs, right.sourceRefs)
    && left.conversationId === right.conversationId;
}

function sameStringList(left: readonly string[], right: readonly string[]): boolean {
  if (left === right) return true;
  if (left.length !== right.length) return false;
  for (let index = 0; index < left.length; index += 1) {
    if (left[index] !== right[index]) return false;
  }
  return true;
}

function sameToolInput(
  left: ToolFactValue | undefined,
  right: ToolFactValue | undefined,
): boolean {
  return isDeepStrictEqual(left, right);
}

function sameErrorFacts(
  left: ToolErrorFacts | undefined,
  right: ToolErrorFacts | undefined,
): boolean {
  return isDeepStrictEqual(left, right);
}

function sameAttachmentRefs(
  left: readonly ModelInputAttachmentRef[] | undefined,
  right: readonly ModelInputAttachmentRef[] | undefined,
): boolean {
  if (left === right) return true;
  if (left === undefined || right === undefined) return false;
  if (left.length !== right.length) return false;
  return left.every((item, index) => {
    const other = right[index];
    if (other === undefined) return false;
    return item.kind === other.kind
      && item.mimeType === other.mimeType
      && item.attachmentId === other.attachmentId
      && item.inputRef === other.inputRef
      && item.byteLength === other.byteLength
      && item.sha256 === other.sha256;
  });
}

function sameDelegatedExecution(
  left: DelegatedAgentExecutionMetadata | undefined,
  right: DelegatedAgentExecutionMetadata | undefined,
): boolean {
  if (left === right) return true;
  if (left === undefined || right === undefined) return false;
  return left.modelRounds === right.modelRounds
    && left.toolCallCount === right.toolCallCount
    && isDeepStrictEqual(left.usage, right.usage);
}

